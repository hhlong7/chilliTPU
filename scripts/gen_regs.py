"""Generate dnn_regs_pkg.sv, dnn_regs.h, and dnn_regs.py from spec/regmap.yaml.

Usage (from the repo root):
    python3 scripts/gen_regs.py            # or `make regs`
    python3 scripts/gen_regs.py --check    # validate the YAML only

spec/regmap.yaml is the single source of truth. This script checks it (aligned,
unique, in-range offsets; fields inside the data width and not overlapping) and
writes the same constants for the three languages, so RTL, firmware, and Python
can never disagree about an address or bit position:
    rtl/pkg/dnn_regs_pkg.sv   <REG>_ADDR, <REG>_<FIELD>_LSB / _W / _MASK
    fw/src/dnn_regs.h         DNN_<REG>_ADDR, DNN_<REG>_<FIELD>_SHIFT / _MASK (mask in place)
    sw/py/dnn_regs.py         same names as the header, plus a REGS table
The outputs are generated (gitignored); never edit them by hand.
"""
from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[1]
ACCESS = {"rw", "ro", "wo", "w1c"}
IDENT = re.compile(r"^[A-Z][A-Z0-9_]*$")


@dataclass
class Field:
    name: str
    msb: int
    lsb: int
    desc: str

    @property
    def width(self) -> int:
        return self.msb - self.lsb + 1

    @property
    def mask(self) -> int:          # in place (already shifted)
        return ((1 << self.width) - 1) << self.lsb


@dataclass
class Reg:
    name: str
    offset: int
    access: str
    fields: list[Field]


class RegmapError(ValueError):
    pass


def parse_bits(bits: str) -> tuple[int, int]:
    m = re.fullmatch(r"\s*(\d+)\s*(?::\s*(\d+)\s*)?", str(bits))
    if not m:
        raise RegmapError(f"bad bits {bits!r} (use \"7\" or \"7:4\")")
    msb = int(m.group(1))
    lsb = int(m.group(2)) if m.group(2) is not None else msb
    if lsb > msb:
        raise RegmapError(f"bits {bits!r}: msb must be >= lsb")
    return msb, lsb


def load(path: Path) -> tuple[dict, list[Reg]]:
    doc = yaml.safe_load(path.read_text())
    meta = doc.get("meta") or {}
    for key in ("name", "data_width", "addr_width"):
        if key not in meta:
            raise RegmapError(f"meta.{key} is missing")
    dw, aw = int(meta["data_width"]), int(meta["addr_width"])
    regs, offsets, names = [], {}, set()
    for r in doc.get("registers") or []:
        name = str(r.get("name", ""))
        if not IDENT.match(name):
            raise RegmapError(f"register name {name!r} must be UPPER_SNAKE_CASE")
        if name in names:
            raise RegmapError(f"duplicate register {name}")
        names.add(name)
        off = int(r["offset"])
        if off % (dw // 8):
            raise RegmapError(f"{name}: offset {off:#x} not aligned to {dw // 8} bytes")
        if off >= (1 << aw):
            raise RegmapError(f"{name}: offset {off:#x} outside {aw}-bit address space")
        if off in offsets:
            raise RegmapError(f"{name}: offset {off:#x} already used by {offsets[off]}")
        offsets[off] = name
        access = str(r.get("access", "")).lower()
        if access not in ACCESS:
            raise RegmapError(f"{name}: access must be one of {sorted(ACCESS)}")
        fields, used, fnames = [], 0, set()
        for f in r.get("fields") or []:
            fname = str(f.get("name", ""))
            if not IDENT.match(fname) or fname in fnames:
                raise RegmapError(f"{name}: bad or duplicate field name {fname!r}")
            fnames.add(fname)
            msb, lsb = parse_bits(f["bits"])
            if msb >= dw:
                raise RegmapError(f"{name}.{fname}: bit {msb} outside {dw}-bit register")
            fld = Field(fname, msb, lsb, str(f.get("desc", "")))
            if used & fld.mask:
                raise RegmapError(f"{name}.{fname}: bits overlap another field")
            used |= fld.mask
            fields.append(fld)
        if not fields:
            raise RegmapError(f"{name}: needs at least one field")
        regs.append(Reg(name, off, access, fields))
    if not regs:
        raise RegmapError("no registers defined")
    return meta, sorted(regs, key=lambda r: r.offset)


HEADER = "Generated by scripts/gen_regs.py from spec/regmap.yaml. Do not edit."


def gen_sv(meta: dict, regs: list[Reg]) -> str:
    aw, dw = int(meta["addr_width"]), int(meta["data_width"])
    pkg = f"{meta['name']}_regs_pkg"
    out = [f"// {pkg}.sv - {HEADER}", "", f"package {pkg};", "",
           f"  localparam int REG_ADDR_W = {aw};", f"  localparam int REG_DATA_W = {dw};",
           f"  localparam int REGMAP_VERSION = {int(meta.get('version', 0))};", ""]
    for r in regs:
        out.append(f"  // {r.name} ({r.access})")
        out.append(f"  localparam logic [{aw - 1}:0] {r.name}_ADDR = {aw}'h{r.offset:0{(aw + 3) // 4}X};")
        for f in r.fields:
            out.append(f"  localparam int {r.name}_{f.name}_LSB = {f.lsb};   // {f.desc}")
            out.append(f"  localparam int {r.name}_{f.name}_W   = {f.width};")
            out.append(f"  localparam logic [{dw - 1}:0] {r.name}_{f.name}_MASK = {dw}'h{f.mask:0{dw // 4}X};")
        out.append("")
    out += [f"endpackage : {pkg}", ""]
    return "\n".join(out)


def gen_c(meta: dict, regs: list[Reg]) -> str:
    p = str(meta["name"]).upper()
    guard = f"{p}_REGS_H"
    out = [f"/* {meta['name']}_regs.h - {HEADER} */", f"#ifndef {guard}", f"#define {guard}", "",
           f"#define {p}_REGMAP_VERSION {int(meta.get('version', 0))}u", ""]
    for r in regs:
        out.append(f"/* {r.name} ({r.access}) */")
        out.append(f"#define {p}_{r.name}_ADDR 0x{r.offset:03X}u")
        for f in r.fields:
            out.append(f"#define {p}_{r.name}_{f.name}_SHIFT {f.lsb}u  /* {f.desc} */")
            out.append(f"#define {p}_{r.name}_{f.name}_MASK  0x{f.mask:08X}u")
        out.append("")
    out += [f"#endif /* {guard} */", ""]
    return "\n".join(out)


def gen_py(meta: dict, regs: list[Reg]) -> str:
    p = str(meta["name"]).upper()
    out = [f'"""{meta["name"]}_regs.py - {HEADER}"""', "",
           f"{p}_REGMAP_VERSION = {int(meta.get('version', 0))}", ""]
    for r in regs:
        out.append(f"{p}_{r.name}_ADDR = 0x{r.offset:03X}")
        for f in r.fields:
            out.append(f"{p}_{r.name}_{f.name}_SHIFT = {f.lsb}")
            out.append(f"{p}_{r.name}_{f.name}_MASK = 0x{f.mask:08X}")
    out += ["", "# name -> (addr, access, {field: (lsb, width)})", "REGS = {"]
    for r in regs:
        fields = ", ".join(f'"{f.name}": ({f.lsb}, {f.width})' for f in r.fields)
        out.append(f'    "{r.name}": (0x{r.offset:03X}, "{r.access}", {{{fields}}}),')
    out += ["}", ""]
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Generate register files from spec/regmap.yaml.")
    ap.add_argument("--regmap", type=Path, default=REPO / "spec" / "regmap.yaml")
    ap.add_argument("--out-root", type=Path, default=REPO, help="repo root to write under (tests use a temp dir)")
    ap.add_argument("--check", action="store_true", help="validate only, write nothing")
    args = ap.parse_args(argv)
    try:
        meta, regs = load(args.regmap)
    except (RegmapError, KeyError, TypeError, ValueError) as exc:
        print(f"gen_regs.py: {args.regmap}: {exc}", file=sys.stderr)
        return 1
    if args.check:
        print(f"gen_regs.py: {args.regmap.name} OK ({len(regs)} registers)")
        return 0
    name = meta["name"]
    outputs = {
        args.out_root / "rtl" / "pkg" / f"{name}_regs_pkg.sv": gen_sv(meta, regs),
        args.out_root / "fw" / "src" / f"{name}_regs.h": gen_c(meta, regs),
        args.out_root / "sw" / "py" / f"{name}_regs.py": gen_py(meta, regs),
    }
    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        print(f"gen_regs.py: wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
